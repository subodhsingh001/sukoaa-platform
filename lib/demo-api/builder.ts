import {parseDocument} from 'yaml';
import {HttpError} from '../platform/http';
export type Value=string|number|boolean|null;
export type RecordRow=Record<string,unknown>&{id:number};
export type Tables=Record<string,RecordRow[]>;
export type ApiConfig={resources:Record<string,{count:number;fields:Record<string,string>;relations?:Record<string,{resource:string;foreignKey:string}>}>};
const reserved=new Set(['graphql','reset','config','sync','export','__proto__','constructor','prototype','Query','Mutation','JSON']);
export function identifier(s:unknown):s is string{return typeof s==='string'&&/^[a-zA-Z][a-zA-Z0-9_]{0,35}$/.test(s)&&!reserved.has(s);}
export function parseConfig(source:string):ApiConfig{
 if(typeof source!=='string'||source.length>20000)throw new HttpError(400,'Keep configuration under 20,000 characters.');
 let value:unknown;try{const doc=parseDocument(source,{uniqueKeys:true});if(doc.errors.length)throw Error(doc.errors[0].message);value=doc.toJS({maxAliasCount:0});}catch{throw new HttpError(400,'Invalid JSON/YAML. Aliases and duplicate keys are not supported.');}
 return validateConfig(value);
}
export function validateConfig(value:unknown):ApiConfig{
 const r=(value as ApiConfig)?.resources;if(!r||typeof r!=='object'||Array.isArray(r)||Object.keys(r).length<1||Object.keys(r).length>12)throw new HttpError(400,'Define 1–12 resources.');
 for(const name of Object.keys(r))if(Object.hasOwn(r,name+'ById'))throw new HttpError(400,'Resource names must not collide with generated ById query names.');
 const clean:ApiConfig={resources:{}};let total=0;
 for(const [name,v]of Object.entries(r)){
  if(!identifier(name)||!v||typeof v!=='object'||!Number.isInteger(v.count)||v.count<1||v.count>100)throw new HttpError(400,'Use safe resource names and record counts from 1 to 100.');
  total+=v.count;if(total>1000)throw new HttpError(400,'Generate at most 1,000 records.');
  if(!v.fields||typeof v.fields!=='object'||Array.isArray(v.fields)||Object.keys(v.fields).length>20)throw new HttpError(400,'Use at most 20 fields per resource.');
  const fields:Record<string,string>={};for(const [key,kind]of Object.entries(v.fields)){
   if(!identifier(key)||key==='id'||typeof kind!=='string'||kind.length>150||!(/^(string|name|email|integer|number|boolean|date|text)$/.test(kind)||/^ref:[a-zA-Z][a-zA-Z0-9_]{0,35}$/.test(kind)||/^enum:[a-zA-Z0-9 _-]+(?:\|[a-zA-Z0-9 _-]+){1,11}$/.test(kind)))throw new HttpError(400,'Unsupported field. Use string, name, email, text, integer, number, boolean, date, enum:a|b or ref:resource.');fields[key]=kind;
  }
  const relations:NonNullable<ApiConfig['resources'][string]['relations']>={};if(v.relations){if(typeof v.relations!=='object'||Array.isArray(v.relations)||Object.keys(v.relations).length>8)throw new HttpError(400,'Use at most 8 relationships per resource.');for(const [key,rel]of Object.entries(v.relations)){if(!identifier(key)||key in fields||key==='id'||!rel||!identifier(rel.resource)||!identifier(rel.foreignKey))throw new HttpError(400,'Invalid relationship.');relations[key]={resource:rel.resource,foreignKey:rel.foreignKey};}}
  clean.resources[name]={count:v.count,fields,relations};
 }
 for(const v of Object.values(clean.resources)){for(const kind of Object.values(v.fields))if(kind.startsWith('ref:')&&!Object.hasOwn(clean.resources,kind.slice(4)))throw new HttpError(400,'Reference points to an unknown resource.');for(const rel of Object.values(v.relations||{})){if(!clean.resources[rel.resource]?.fields[rel.foreignKey])throw new HttpError(400,'Relationship requires an existing foreign key field.');}}
 return clean;
}
export function generateTables(config:ApiConfig):Tables{
 const tables:Tables={};
 for(const [name,r]of Object.entries(config.resources)){
  tables[name]=Array.from({length:r.count},(_,i)=>{
   const row:RecordRow={id:i+1};
   for(const [key,type]of Object.entries(r.fields)){
    const enums=type.startsWith('enum:')?type.slice(5).split('|'):[];
    row[key]=type.startsWith('ref:')?i%config.resources[type.slice(4)].count+1:enums.length?enums[i%enums.length]:type==='integer'?i+1:type==='number'?(i+1)*12.5:type==='boolean'?i%2===0:type==='email'?`person${i+1}@example.com`:type==='name'?['Asha','Subo','Cora','Dev'][i%4]+' Example '+(i+1):type==='date'?`2026-01-${String(i%28+1).padStart(2,'0')}`:type==='text'?`Fictional ${name} record ${i+1} for testing.`:`${key} ${i+1}`;
   }return row;
  });
 }return tables;
}
